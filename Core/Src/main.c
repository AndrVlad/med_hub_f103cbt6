uint32_t calculateCRC32(uint8_t* arg,uint16_t length) {
  uint32_t crc_f = 0xFFFFFFFF; 	// Начальное значение CRC
    for (int i=0;i<length;i++)
    {crc_f=crc32_table[(crc_f ^ arg[i]) & 0xFF] ^ (crc_f >> 8);}
  return ~crc_f;
}

void fillRequestFrame(uint8_t command_code) {
	// формирование ответа
		memset(request_buf,0,FRAME_LEN);
		request_buf[0] = 0xFA;
		request_buf[1] = 0xAF;
		request_buf[2] = command_code;

		request_buf[258] = 0xFF;
		request_buf[259] = 0x0D;

		uint32_t crc = calculateCRC32(request_buf,FRAME_LEN-4);
		request_buf[260] = (crc >> 24) & 0xFF;
		request_buf[261] = (crc >> 16) & 0xFF;
		request_buf[262] = (crc >> 8) & 0xFF;
		request_buf[263] = crc & 0xFF;
}

